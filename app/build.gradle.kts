val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) {
        load(FileInputStream(keystorePropsFile))
    }
}

fun keystoreValue(key: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(key)

val releaseStoreFile = keystoreValue("KEYSTORE_FILE")
val releaseStorePassword = keystoreValue("KEYSTORE_PASSWORD")
val releaseKeyAlias = keystoreValue("KEY_ALIAS")
val releaseKeyPassword = keystoreValue("KEY_PASSWORD")

